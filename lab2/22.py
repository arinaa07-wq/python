import doctest
def f():
    """
    Вычисляет количество цифр '3' в четверичной записи числа 16**18 * 4**10 - 46 - 16.
Алгоритм:
    1. Вычисляем значение выражения
    2. Переводим число в четверичную систему счисления
    3. Считаем количество троек

    >>> f()
    43
    """
    n = 16**18 * 4**10 - 46 - 16
    k = 0
    while n != 0:
        c = n % 4
        n = n // 4
        if c == 3:
            k = k + 1
    return k  # возвращаем результат


# Для запуска при прямом выполнении скрипта
if __name__ == "__main__":
    print(f())
doctest.testmod(verbose=True)