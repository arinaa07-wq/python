from openpyxl import Workbook #(для работы с Excel)
from datetime import datetime #для работы с датой и временем

def save_to_excel(rows, filename="report.xlsx"):
    """
    СОХРАНЯЕТ ИСТОРИЮ РАСЧЕТОВ В ФАЙЛ EXCEL
    ЧТО ПРИНИМАЕТ:
        rows (list)    - список записей из базы данных 
        filename (str) - имя файла для сохранения 
    
    ЧТО ДЕЛАЕТ:
        1. Проверяет, есть ли данные
        2. Создает новую Excel-книгу
        3. Добавляет заголовки таблицы
        4. Записывает все строки с данными
        5. Сохраняет файл
    ЧТО ВОЗВРАЩАЕТ:
        True - если сохранилось успешно
        False - если данных нет
    """
    if not rows: #проверяет, пустой ли список
        print("Нет данных для сохранения")
        return False
    # Workbook() - создает пустой Excel-файл
    wb = Workbook()
    ws = wb.active # берем первый лист по умолчанию
    ws.title = "Расчеты" #Переименовывает вкладку внизу Excel-файла.
    
    # Создает список с названиями колонок
    #Первая строка в Excel будет содержать эти слова.
    headers = ["ID", "Расстояние (км)", "Тип авто", "Груженый", "Тип расчета", "Результат"]
    ws.append(headers) #Вставляет строку с заголовками в Excel
    
    # Данные
    for row in rows: #Перебирает каждую запись по очереди
        ws.append(list(row)) #Добавляет одну запись как новую строку 
    
    wb.save(filename) #Сохраняет Excel-файл 
    print(f"Сохранено в {filename}")
    return True